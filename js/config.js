// 1. הגדרת מספר הטלפון המרכזי של מיטב
// חובה: להקפיד על קידומת 972 ללא פלוס וללא אפס בהתחלה 
// דוגמה: 972501234567
const MEITAV_PHONE = "972509161025"; // <-- החלף את המספר הזה במספר האמיתי שלה

// ==========================================
// מערכת החלפת קישורים אוטומטית
// ==========================================
document.addEventListener("DOMContentLoaded", () => {
    // מציאת כל הקישורים שמכילים את המילה wa.me (קישורי וואטסאפ)
    const waLinks = document.querySelectorAll('a[href*="wa.me"]');
    
    waLinks.forEach(link => {
        // החלפת מספר הדמה 972000000000 במספר האמיתי שהוגדר למעלה
        if (link.href.includes("972000000000")) {
            link.href = link.href.replace("972000000000", MEITAV_PHONE);
        }
    });
    
    console.log(`✅ ${waLinks.length} WhatsApp links updated dynamically!`);
});